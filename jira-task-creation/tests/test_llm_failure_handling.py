def test_the_breakdown_context_does_not_ask_the_model_to_judge_duplicates() -> None:
    context = ProjectContext(
        name="BGV",
        description="Background checks.",
        existing_titles=("BGV-65 — Implement Address Verification",),
    )
    breakdown_text = context.as_prompt_text(for_breakdown=True)
    triage_text = context.as_prompt_text()
    assert "BGV-65" in breakdown_text
    assert "say so" not in breakdown_text
    # Triage no longer sees them at all: on fresh BGV-15 it asked "does this
    # differ from BGV-2?" instead of the duplicate check answering (2026-09-25).
    assert "BGV-65" not in triage_text


async def test_a_triage_shaped_answer_is_a_short_readable_error(monkeypatch) -> None:
    """The exact live answer: a verdict object where a breakdown belonged."""

    async def _chat(prompt: str) -> str:
        return (
            '{"verdict": "CLARIFICATION_REQUIRED", "reason": "thin", '
            '"questions": ["Which candidates?"]}'
        )

    monkeypatch.setattr(decompose, "_chat", _chat)
    with pytest.raises(DecompositionError) as caught:
        await decompose.llm_breakdown("Record address history.", ProjectContext())
    message = str(caught.value)
    assert "did not match the breakdown format" in message
    assert "missing: classification" in message
    assert "unexpected: verdict" in message
    assert "errors.pydantic.dev" not in message
    assert len(message) < 300
